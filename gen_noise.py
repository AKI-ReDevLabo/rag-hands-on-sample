FORBIDDEN = [
    "数量変更", "締切", "休止", "返品", "不良", "クレーム", "ロット", "寮", "定員", "認定",
    "常駐", "異動", "帰省", "経費", "精算", "在宅", "VPN", "パスワード", "規格", "等級",
    "予冷", "日持ち", "淡", "薄", "切り花", "会議", "拠点は", "つの拠点",
]
FORBIDDEN_RE = [r"\d+\s*(?:名|人)", r"\d+\s*件"]


def check_forbidden(name: str, body: str) -> None:
    for w in FORBIDDEN:
        if w in body:
            raise ValueError(f"{name}: 禁止語「{w}」が含まれています")
    for pat in FORBIDDEN_RE:
        m = re.search(pat, body)
        if m:
            raise ValueError(f"{name}: 禁止パターン「{m.group(0)}」が含まれています")


def main() -> None:
    files: dict[str, str] = {}
    for year in (2024, 2025):
        for region, crop, m, days in CYCLES:
            t, b = gen_cultivation(region, crop, m, days, year)
            files[f"栽培記録/{t}.md"] = b
    d = date(2024, 10, 1)
    while d <= date(2026, 9, 1):
        for region in ("I県", "N県", "S県"):
            t, b = gen_diary(region, d.year, d.month)
            files[f"作業日誌/{t}.md"] = b
        d = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
    d, no = date(2023, 4, 1), 1
    while d <= date(2026, 9, 1):
        t, b = gen_newsletter(no, d.year, d.month)
        files[f"会報誌/{t}.md"] = b
        d = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
        no += 1

    for name, body in files.items():
        check_forbidden(name, body)

    if OUT.exists():
        shutil.rmtree(OUT)
    for rel, body in files.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")
    total = sum(len(b) for b in files.values())
    print(f"{len(files)} ファイル作成  {total:,} 文字  → {OUT}")


if __name__ == "__main__":
    main()
