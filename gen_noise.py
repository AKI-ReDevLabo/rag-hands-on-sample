def measure(unit: str, progress: float) -> str:
    base = {"草丈": 60, "葉数": 18, "株張り": 40, "葉幅": 10, "葉鞘径": 25, "葉長": 45,
            "根径": 70, "根長": 35, "株径": 45, "結球径": 16, "外葉数": 20, "花蕾径": 14,
            "葉柄長": 40, "株重": 900, "節数": 40, "茎径": 8, "分枝数": 10, "切り枝長": 80,
            "ベーサル本数": 3, "側枝数": 8, "花茎数": 15, "花茎長": 70, "茎数": 12,
            "樹高": 80, "枝数": 30}[unit]
    suffix = {"草丈": "cm", "株張り": "cm", "葉幅": "cm", "葉鞘径": "mm", "葉長": "cm",
              "根径": "mm", "根長": "cm", "株径": "cm", "結球径": "cm", "花蕾径": "cm",
              "葉柄長": "cm", "株重": "g", "茎径": "mm", "切り枝長": "cm", "花茎長": "cm",
              "樹高": "cm"}.get(unit, "")
    v = base * max(0.05, min(1.1, progress)) * R.uniform(0.85, 1.15)
    if unit in COUNT_UNITS:
        v = max(1, round(v))
    else:
        v = round(v, 1) if v < 10 else int(v)
    return f"{unit}{v}{suffix}"


