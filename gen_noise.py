METERS = {r: {"電力": R.uniform(20000, 90000), "井戸水": R.uniform(3000, 40000)}
          for r in ("I県", "N県", "S県")}


def gen_diary(region: str, year: int, month: int) -> tuple[str, str]:
    title = f"作業日誌_{region}_{year}年{month:02d}月"
    lines = [f"# 作業日誌　{region}拠点　{year}年{month}月", "",
             "各日の天気、作業、来訪、引き継ぎを記録する。", ""]
    meter = METERS[region]
    d = date(year, month, 1)
    while d.month == month:
        heat = 3.0 if region != "S県" and season_of(d.month) == "冬" else 1.0
        meter["電力"] += R.uniform(40, 160) * heat
        meter["井戸水"] += R.uniform(2, 30) / heat
        if (d.month == 1 and d.day <= 3) or (d.weekday() == 6 and R.random() < 0.8):
            d += timedelta(days=1)
            continue
        w, hi, lo = weather(region, d)
        lines.append(f"## {jdate(d)}　{w}　最高{hi}度／最低{lo}度")
        crops = active_crops(region, month)
        if crops:
            for crop in pick(crops, R.randint(1, 2)):
                k = CROPS[crop]["kind"]
                lines.append(f"- {crop}：" + pick(CARE[k] + HARVEST[k]))
        lines.append("- 施設：" + pick(FACILITY[region]))
        lines.append(f"- 検針：電力 {meter['電力']:.1f}kWh、井戸水 {meter['井戸水']:.1f}m3")
        lines.append(f"- 気象：降水量 {R.choice([0.0, 0.0, 0.0, R.uniform(0.5, 60)]):.1f}mm、"
                     f"日照 {R.uniform(0, 11):.1f}時間、最大風速 {R.uniform(0.5, 14):.1f}m/s")
        if R.random() < 0.35:
            lines.append("- 来訪・連絡：" + pick(VISIT))
        if R.random() < 0.25:
            lines.append("- 安全：" + pick(SAFETY))
        if R.random() < 0.5:
            lines.append("- 引き継ぎ：" + pick(HANDOVER))
        lines.append("")
        d += timedelta(days=1)
    return title, "\n".join(lines)


