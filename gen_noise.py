    s = season_of(d.month)
    pool = WEATHER[s]
    if region == "N県" and s == "冬":
        pool = pool + WEATHER_SNOW_NAGANO
    if region == "S県" and s == "夏":
        pool = pool + (["梅雨空"] if d.month == 6 else ["台風接近で風雨強い", "台風一過の晴れ"])
    hi, lo = CLIMATE[region][d.month - 1]
    return pick(pool), hi + R.randint(-4, 4), lo + R.randint(-4, 3)


