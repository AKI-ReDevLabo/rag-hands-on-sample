def active_crops(region: str, month: int) -> list[str]:
    out = []
    for reg, crop, m, days in CYCLES:
        if reg != region:
            continue
        # 開始月から期間の月数だけ有効とみなす
        span = max(1, days // 30)
        if (month - m) % 12 <= span:
            out.append(crop)
    return out


